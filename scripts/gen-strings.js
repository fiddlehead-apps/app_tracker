// Regenerates {Shared,SolaTrackerWatch}/{en,de}.lproj/Localizable.strings from the keys the
// compiler extracted (SWIFT_EMIT_LOC_STRINGS) and scripts/de.json.
// Usage: build once, then `node scripts/gen-strings.js <DerivedData path>`.
const fs = require("fs"), cp = require("child_process"), path = require("path");
const dd = process.argv[2] || "/tmp/solatracker-dd";
const root = path.join(__dirname, "..");
const files = cp.execSync(`find "${dd}/Build/Intermediates.noindex" -name "*.stringsdata"`).toString().trim().split("\n");
// Several builds (archs, targets) leave stringsdata behind; per target and source use the newest.
const newest = new Map();
for (const f of files) {
  const j = JSON.parse(fs.readFileSync(f)), target = f.split("/").find(x => x.endsWith(".build") && !x.startsWith("SolaTracker.build")) || "";
  const key = target + "|" + j.source, m = fs.statSync(f).mtimeMs;
  if (!newest.has(key) || newest.get(key).m < m) newest.set(key, { m, j });
}
const keys = new Set();
for (const { j } of newest.values()) for (const t in j.tables) for (const e of j.tables[t]) keys.add(e.key);
const identity = new Set(["", "%@", "%lld", "0", "·"]);
const de = JSON.parse(fs.readFileSync(path.join(__dirname, "de.json")));
const q = s => '"' + s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n") + '"';
const sorted = [...keys].sort();
const missing = sorted.filter(k => !identity.has(k) && !(k in de));
const unused = Object.keys(de).filter(k => !keys.has(k));
const out = (map) => "/* Generated by scripts/gen-strings.js. Edit scripts/de.json instead. */\n\n" + sorted.map(k => `${q(k)} = ${q(map(k))};`).join("\n") + "\n";
// Shared/ serves the app and the widget, SolaTrackerWatch/ the watch app.
for (const dir of ["Shared", "SolaTrackerWatch"]) {
  fs.writeFileSync(path.join(root, dir, "en.lproj/Localizable.strings"), out(k => k));
  fs.writeFileSync(path.join(root, dir, "de.lproj/Localizable.strings"), out(k => de[k] ?? k));
}
console.log(`${sorted.length} keys. Missing German: ${missing.length ? missing.join(" | ") : "none"}. Unused: ${unused.length ? unused.join(" | ") : "none"}.`);
